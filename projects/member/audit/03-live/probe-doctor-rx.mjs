await p.goto(DOC+'/login',{waitUntil:'domcontentloaded'});await p.waitForLoadState('networkidle');
await p.locator('input[type=email]').fill('anil@doctor.com');
await p.locator('input[type=password]').fill('Doctor@123');
await p.getByRole('button',{name:/sign in|log ?in/i}).click();
await p.waitForTimeout(5000);
